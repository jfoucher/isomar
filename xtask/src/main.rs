//! Project tasks. `cargo xtask tokens --swift <out.swift>` writes the design tokens
//! (`data/design/tokens.json`) as Swift for the macOS, iOS and iPadOS apps' chrome, and
//! `--kotlin <out.kt>` as Kotlin for the Android app's; the renderer gets the same file through
//! `isomar-app/build.rs`, the GTK app its CSS through its own build script.
//! `cargo xtask naturalearth <dir>` builds the bundle of Natural Earth names and their centrelines.
//! `cargo xtask capes <dir> [--coves]` packs OpenStreetMap's named capes, or its bays and coves.

mod capes;
mod naturalearth;

use serde_json::Value;
use std::fmt::Write;
use std::path::Path;

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("tokens") => tokens(&args[1..]),
        Some("naturalearth") => naturalearth::run(&args[1..]),
        Some("capes") => capes::run(&args[1..]),
        _ => {
            eprintln!("usage: cargo xtask tokens [--swift <out.swift>] [--kotlin <out.kt>]\n       cargo xtask naturalearth <dir> [--out data/labels/naturalearth.json.gz]\n       cargo xtask capes <dir> [--coves] [--out data/labels/capes.json.gz]");
            std::process::exit(2);
        }
    }
}

fn tokens(args: &[String]) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let json: Value = serde_json::from_str(&std::fs::read_to_string(root.join("data/design/tokens.json")).expect("tokens.json")).expect("JSON");
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--swift" => {
                let out = args.get(i + 1).expect("--swift needs a path");
                if let Some(dir) = Path::new(out).parent() {
                    std::fs::create_dir_all(dir).unwrap();
                }
                std::fs::write(out, swift(&json)).unwrap();
                i += 2;
            }
            "--kotlin" => {
                let out = args.get(i + 1).expect("--kotlin needs a path");
                if let Some(dir) = Path::new(out).parent() {
                    std::fs::create_dir_all(dir).unwrap();
                }
                std::fs::write(out, kotlin(&json)).unwrap();
                i += 2;
            }
            other => panic!("unknown argument {other}"),
        }
    }
}

fn camel_lower(name: &str) -> String {
    let mut out = String::new();
    for (i, p) in name.split('-').enumerate() {
        if i == 0 {
            out.push_str(p);
        } else {
            let mut c = p.chars();
            if let Some(f) = c.next() {
                out.extend(f.to_uppercase());
                out.push_str(c.as_str());
            }
        }
    }
    // Swift identifiers cannot start with a digit.
    if out.chars().next().is_some_and(|c| c.is_ascii_digit()) { format!("_{out}") } else { out }
}

