/// Seconds for times, the unit's own scale otherwise.
fn number(s: &str) -> f64 {
    let s = s.trim();
    if s.ends_with('s') && !s.ends_with("px") { number_ms(s) / 1000.0 } else { number_ms(s) }
}

fn swift(json: &Value) -> String {
    let mut o = String::new();
    o.push_str("// Generated by `cargo xtask tokens --swift` from data/design/tokens.json. Do not edit.\n\n#if canImport(AppKit)\nimport AppKit\n#else\nimport UIKit\n#endif\nimport SwiftUI\n\n");
    o.push_str("/// The three looks of the app. Setting `current` repaints everything that reads a token.\n");
    o.push_str("enum IsomarThemeID: Int { case day, dusk, night }\n\n");
    o.push_str("enum IsomarTheme {\n    static var current: IsomarThemeID = .day {\n        didSet { NotificationCenter.default.post(name: .isomarThemeChanged, object: nil) }\n    }\n}\n\n");
    o.push_str("extension Notification.Name {\n    static let isomarThemeChanged = Notification.Name(\"isomarThemeChanged\")\n}\n\n");
    o.push_str("/// A colour of the design, with a value in each theme.\nenum Tok: Int, CaseIterable {\n");
    let colours = json["color"]["tokens"].as_array().unwrap();
    for c in colours {
        writeln!(o, "    case {}", camel_lower(c["name"].as_str().unwrap())).unwrap();
    }
    o.push_str("}\n\n");
    o.push_str("extension Tok {\n    /// The token with this name in `tokens.json`, such as `alt-2`.\n    static func byName(_ name: String) -> Tok? { names[name] }\n}\n\nprivate let names: [String: Tok] = [\n");
    for c in colours {
        let n = c["name"].as_str().unwrap();
        writeln!(o, "    \"{n}\": .{},", camel_lower(n)).unwrap();
    }
    o.push_str("]\n\n");
    o.push_str("private let tokenValues: [[(Double, Double, Double, Double)]] = [\n");
    for c in colours {
        let v = &c["value"];
        let f = |k: &str| {
            let (r, g, b, a) = colour(v[k].as_str().unwrap());
            format!("({r:.5}, {g:.5}, {b:.5}, {a:.3})")
        };
        writeln!(o, "    [{}, {}, {}],", f("day"), f("dusk"), f("night")).unwrap();
    }
    o.push_str("]\n\n");
    o.push_str(
        r#"#if canImport(AppKit)
extension NSColor {
    /// The token's colour in the current theme; it follows the theme without being asked again.
    static func isomar(_ token: Tok) -> NSColor {
        NSColor(name: nil) { _ in
            let v = tokenValues[token.rawValue][IsomarTheme.current.rawValue]
            return NSColor(srgbRed: v.0, green: v.1, blue: v.2, alpha: v.3)
        }
    }
}

extension Color {
    static func isomar(_ token: Tok) -> Color { Color(nsColor: .isomar(token)) }
}
#else
extension UIColor {
    /// The token's colour in the current theme; it follows the theme without being asked again.
    static func isomar(_ token: Tok) -> UIColor {
        UIColor { _ in
            let v = tokenValues[token.rawValue][IsomarTheme.current.rawValue]
            return UIColor(red: v.0, green: v.1, blue: v.2, alpha: v.3)
        }
    }
}

extension Color {
    static func isomar(_ token: Tok) -> Color { Color(uiColor: .isomar(token)) }
}
#endif

"#,
    );
    for (group, name) in [("size", "Size"), ("stroke", "Stroke"), ("spacing", "Space"), ("radius", "Radius"), ("timing", "Timing"), ("chart", "ChartMetric")] {
        writeln!(o, "/// The `{group}` tokens: points, or seconds for timings, or millimetres for the chart's.").unwrap();
        writeln!(o, "enum {name} {{").unwrap();
        for t in json[group]["tokens"].as_array().unwrap() {
            let n = t["name"].as_str().unwrap();
            let n = n.strip_prefix("space-").or_else(|| n.strip_prefix("radius-")).unwrap_or(n);
            writeln!(o, "    static let {}: Double = {:?}", camel_lower(n), number(t["value"].as_str().unwrap())).unwrap();
        }
        o.push_str("}\n\n");
    }
    o
}

/// `camel_lower` with what Kotlin cannot have as a name made safe.
fn kotlin_name(name: &str) -> String {
    camel_lower(name)
}

fn kotlin(json: &Value) -> String {
    let mut o = String::new();
    o.push_str("// Generated by `cargo xtask tokens --kotlin` from data/design/tokens.json. Do not edit.\n\npackage io.github.isomar.ui\n\n");
    o.push_str("import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\n\n");
    o.push_str("/** The three looks of the app. */\nenum class ThemeId { Day, Dusk, Night }\n\n");
    o.push_str("/** A colour of the design, with a value in each theme (ARGB). */\nenum class Tok(private val day: Long, private val dusk: Long, private val night: Long) {\n");
    let colours = json["color"]["tokens"].as_array().unwrap();
    let argb = |v: &Value, k: &str| {
        let (r, g, b, a) = colour(v[k].as_str().unwrap());
        let n = |x: f64| (x * 255.0).round().clamp(0.0, 255.0) as u32;
        format!("0x{:02X}{:02X}{:02X}{:02X}", n(a), n(r), n(g), n(b))
    };
    for (i, c) in colours.iter().enumerate() {
        let v = &c["value"];
        let end = if i + 1 == colours.len() { ";" } else { "," };
        writeln!(o, "    {}({}, {}, {}){end}", kotlin_name(c["name"].as_str().unwrap()), argb(v, "day"), argb(v, "dusk"), argb(v, "night")).unwrap();
    }
    o.push_str("\n    /** The token's colour in `theme`. */\n    fun of(theme: ThemeId): Color = Color(\n        when (theme) {\n            ThemeId.Day -> day\n            ThemeId.Dusk -> dusk\n            ThemeId.Night -> night\n        },\n    )\n\n");
    o.push_str("    companion object {\n        /** The token with this name in `tokens.json`, such as `alt-2`. */\n        fun byName(name: String): Tok? = names[name]\n\n        private val names: Map<String, Tok> = mapOf(\n");
    for c in colours {
        let n = c["name"].as_str().unwrap();
        writeln!(o, "            \"{n}\" to {},", kotlin_name(n)).unwrap();
    }
    o.push_str("        )\n    }\n}\n\n");
    for (group, name, unit) in [("size", "Size", "dp"), ("stroke", "Stroke", "dp"), ("spacing", "Space", "dp"), ("radius", "Radius", "dp"), ("timing", "Timing", "ms"), ("chart", "ChartMetric", "mm")] {
        writeln!(o, "/** The `{group}` tokens{}. */", if unit == "dp" { ", in dp" } else if unit == "ms" { ", in milliseconds" } else { ", in millimetres" }).unwrap();
        writeln!(o, "object {name} {{").unwrap();
        for t in json[group]["tokens"].as_array().unwrap() {
            let n = t["name"].as_str().unwrap();
            let n = n.strip_prefix("space-").or_else(|| n.strip_prefix("radius-")).unwrap_or(n);
            let v = number_ms(t["value"].as_str().unwrap());
            match unit {
                "dp" => writeln!(o, "    val {} = {:?}.dp", kotlin_name(n), v as f32).unwrap(),
                "ms" => writeln!(o, "    const val {}: Long = {}", kotlin_name(n), v.round() as i64).unwrap(),
                _ => writeln!(o, "    const val {}: Float = {:?}f", kotlin_name(n), v as f32).unwrap(),
            }
        }
        o.push_str("}\n\n");
    }
    o
}
