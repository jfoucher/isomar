//! `style-dusk.css`, `style-night.css`) from the design tokens (`data/design/tokens.json`).
//! Each redefines libadwaita's colour variables on `:root`, as `design/design-system/
//! platform-mapping.md` maps them, plus a `--isomar-<token>` variable for every colour token
//! and the shadows; `data/style.css` holds the rules that use them.

