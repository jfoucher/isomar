fn css_colour(s: &str) -> String {
    let (r, g, b, a) = colour(s);
    let c = |v: f64| (v * 255.0).round() as u8;
    if a >= 1.0 { format!("#{:02x}{:02x}{:02x}", c(r), c(g), c(b)) } else { format!("rgba({}, {}, {}, {a})", c(r), c(g), c(b)) }
}

fn stylesheet(json: &Value, theme: &str) -> String {
    let mut by_name = std::collections::HashMap::new();
    for t in json["color"]["tokens"].as_array().expect("colour tokens") {
        let v = t["value"][theme].as_str().unwrap_or_else(|| panic!("{} has no {theme}", t["name"]));
        by_name.insert(t["name"].as_str().unwrap().to_string(), css_colour(v));
    }
    let mut o = format!("/* Generated by isomar-gtk/build.rs from data/design/tokens.json: the {theme} palette. */\n\n:root {{\n");
    for (var, token) in ADWAITA {
        writeln!(o, "  --{var}: {};", by_name.get(*token).unwrap_or_else(|| panic!("no token {token}"))).unwrap();
    }
    for t in json["color"]["tokens"].as_array().unwrap() {
        let n = t["name"].as_str().unwrap();
        writeln!(o, "  --isomar-{n}: {};", by_name[n]).unwrap();
    }
    for t in json["shadow"]["tokens"].as_array().expect("shadow tokens") {
        let v = t["value"][theme].as_str().unwrap();
        writeln!(o, "  --isomar-{}: {v};", t["name"].as_str().unwrap()).unwrap();
    }
    for group in ["spacing", "radius"] {
        for t in json[group]["tokens"].as_array().unwrap() {
            writeln!(o, "  --isomar-{}: {}px;", t["name"].as_str().unwrap(), number_ms(t["value"].as_str().unwrap())).unwrap();
        }
    }
    o.push_str("}\n");
    o
}

fn main() {
    println!("cargo:rerun-if-changed={TOKENS}");
    println!("cargo:rerun-if-changed=../../data/design/parse.rs");
    let json: Value = serde_json::from_str(&std::fs::read_to_string(TOKENS).expect("tokens.json")).expect("tokens.json is JSON");
    let dir = std::env::var("OUT_DIR").unwrap();
    for theme in ["day", "dusk", "night"] {
        std::fs::write(format!("{dir}/style-{theme}.css"), stylesheet(&json, theme)).unwrap();
    }

    glib_build_tools::compile_resources(&["../../data"], "../../data/resources.gresource.xml", "isomar.gresource");
}
